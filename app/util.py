"""Small shared helpers: UUIDv7, time-zone conversion, duration formatting.

DB convention: timestamps are stored as *naive UTC* datetimes. All conversions between UTC and
local time (Europe/Berlin) go through this module. Functions accepting datetimes treat naive values
as UTC and aware values by their own offset.
"""

from __future__ import annotations

import os
import threading
import time
import uuid
from datetime import UTC, date, datetime, time as dtime, timedelta
from zoneinfo import ZoneInfo

LOCAL_TZ = ZoneInfo("Europe/Berlin")

# --------------------------------------------------------------------------- UUIDv7 (RFC 9562)

_uuid7_lock = threading.Lock()
_uuid7_last_ms = 0
_uuid7_counter = 0
_COUNTER_BITS = 12  # rand_a is used as a monotonic counter (RFC 9562, §6.2 method 1)
_COUNTER_MAX = (1 << _COUNTER_BITS) - 1


def uuid7() -> str:
    """Return a new UUIDv7 as canonical lowercase string.

    Layout: 48-bit Unix ms timestamp | ver=7 | 12-bit counter | var=0b10 | 62 random bits.
    Within the same millisecond the counter increments, so IDs generated by this process are
    strictly increasing (also as strings). On counter overflow the timestamp is advanced by 1 ms.
    """
    global _uuid7_last_ms, _uuid7_counter
    with _uuid7_lock:
        ms = time.time_ns() // 1_000_000
        if ms > _uuid7_last_ms:
            _uuid7_last_ms = ms
            # Random start, top bit cleared to leave headroom for increments.
            _uuid7_counter = int.from_bytes(os.urandom(2), "big") & (_COUNTER_MAX >> 1)
        else:
            _uuid7_counter += 1
            if _uuid7_counter > _COUNTER_MAX:
                _uuid7_last_ms += 1
                _uuid7_counter = 0
        ms, counter = _uuid7_last_ms, _uuid7_counter

    rand_b = int.from_bytes(os.urandom(8), "big") & ((1 << 62) - 1)
    value = (ms & ((1 << 48) - 1)) << 80
    value |= 0x7 << 76
    value |= counter << 64
    value |= 0b10 << 62
    value |= rand_b
    return str(uuid.UUID(int=value))


def uuid7_time(value: str) -> datetime:
    """Extract the embedded timestamp of a UUIDv7 (naive UTC)."""
    ms = uuid.UUID(value).int >> 80
    return datetime.fromtimestamp(ms / 1000, UTC).replace(tzinfo=None)


# --------------------------------------------------------------------------- time helpers


def now_utc() -> datetime:
    """Current time as naive UTC datetime (DB storage format)."""
    return datetime.now(UTC).replace(tzinfo=None)


def as_utc_aware(dt: datetime) -> datetime:
    """Interpret naive datetimes as UTC and return an aware UTC datetime."""
    if dt.tzinfo is None:
        return dt.replace(tzinfo=UTC)
    return dt.astimezone(UTC)


def to_utc_naive(dt: datetime) -> datetime:
    """Normalize any datetime to naive UTC for storage. Naive input is assumed to be UTC."""
    return as_utc_aware(dt).replace(tzinfo=None)


def to_local(dt: datetime) -> datetime:
    """Convert a (naive-UTC or aware) datetime to an aware Europe/Berlin datetime."""
    return as_utc_aware(dt).astimezone(LOCAL_TZ)


def local_date(dt: datetime) -> date:
    """Local calendar day (Europe/Berlin) a UTC timestamp belongs to."""
    return to_local(dt).date()


def today_local() -> date:
    return datetime.now(LOCAL_TZ).date()


def local_to_utc(d: date, t: dtime) -> datetime:
    """Local wall-clock date+time in Europe/Berlin -> naive UTC.

    For ambiguous times (DST end) the first occurrence (fold=0) is used; non-existent times
    (DST start gap) are shifted forward by zoneinfo semantics.
    """
    local = datetime.combine(d, t).replace(tzinfo=LOCAL_TZ)
    return to_utc_naive(local)


def local_midnight_utc(d: date) -> datetime:
    """Start of local day ``d`` (00:00 Europe/Berlin) as naive UTC."""
    return local_to_utc(d, dtime(0, 0))


def local_day_bounds_utc(d: date) -> tuple[datetime, datetime]:
    """[start, end) of local day ``d`` as naive UTC; length is 23/24/25 h around DST changes."""
    return local_midnight_utc(d), local_midnight_utc(d + timedelta(days=1))


# --------------------------------------------------------------------------- formatting


def fmt_hm(seconds: int | float | None, *, plus: bool = False, empty: str = "") -> str:
    """Format a duration in seconds as ``h:mm`` (rounded to the nearest minute).

    Negative values keep their sign: ``-11100`` -> ``"-3:05"``. ``plus=True`` prefixes
    positive values with ``+`` (useful for saldo display). ``None`` -> ``empty``.
    """
    if seconds is None:
        return empty
    total_minutes = int((abs(seconds) + 30) // 60)
    hours, minutes = divmod(total_minutes, 60)
    sign = ""
    if total_minutes:
        if seconds < 0:
            sign = "-"
        elif plus:
            sign = "+"
    return f"{sign}{hours}:{minutes:02d}"


def fmt_dec(seconds: int | float | None, *, places: int = 2, sep: str = ",", plus: bool = False,
            empty: str = "") -> str:
    """Format seconds as decimal hours, German comma by default: ``9000`` -> ``"2,50"``."""
    if seconds is None:
        return empty
    hours = round(seconds / 3600, places)
    if hours == 0:
        hours = 0.0  # avoid "-0,00"
    text = f"{hours:+.{places}f}" if plus and hours > 0 else f"{hours:.{places}f}"
    return text.replace(".", sep) if sep != "." else text
